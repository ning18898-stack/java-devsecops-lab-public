import { test, expect } from '@playwright/test'

test('真实 FastAPI 数据：总览、运行、筛选、详情、证据与审计', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '安全态势总览' })).toBeVisible()
  await expect(page.locator('.metric').filter({ hasText: '工具观察项' }).locator('strong')).toHaveText('5')
  await expect(page.locator('.metric').filter({ hasText: '独立漏洞数' })).toContainText('待确认')
  await expect(page.locator('.tool-result').filter({ hasText: 'ZAP' })).toContainText('执行成功')
  await page.getByLabel('运行标识').fill('release-example-001')
  await page.getByRole('button', { name: '导入运行' }).click()
  await expect(page.getByRole('status')).toContainText('该运行已导入')
  await page.screenshot({ path: `${process.env.P5_EVIDENCE_DIR}/overview.png`, fullPage: true })
  await page.getByRole('link', { name: '◷ 扫描历史' }).click()
  await expect(page.getByRole('heading', { name: '扫描历史', exact: true })).toBeVisible()
  await page.locator('.run-card .text-button').first().click()
  await expect(page.getByRole('heading', { name: '运行详情' })).toBeVisible()
  await expect(page.getByText('该运行共有 5 个观察项', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: '◎ 发现与漏洞管理' }).click()
  await page.getByLabel('来源', { exact: true }).selectOption('codeql')
  await page.getByRole('button', { name: '筛选', exact: true }).click()
  await expect(page.locator('.finding-row')).toHaveCount(3)
  await page.getByLabel('来源', { exact: true }).selectOption('')
  await page.getByLabel('状态', { exact: true }).selectOption('unreviewed')
  await page.getByRole('button', { name: '筛选', exact: true }).click()
  await page.locator('.finding-row').first().click()
  await expect(page.getByRole('heading', { name: '发现详情与处置' })).toBeVisible()
  await expect(page.locator('.observation pre').first()).toBeVisible()
  await page.locator('.observation .evidence-list button').first().click()
  await expect(page.getByRole('dialog')).toContainText('SHA-256')
  await expect(page.getByRole('dialog').locator('pre')).toBeVisible()
  await page.getByRole('button', { name: '关闭预览' }).click()
  await page.getByLabel('下一状态').selectOption('confirmed')
  await page.getByLabel('操作依据').fill('Phase 5 隔离验收：按封存实验说明确认报告需修复')
  await page.getByRole('button', { name: '更新状态', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('操作已持久化')
  await expect(page.locator('.timeline')).toContainText('待研判 → 已确认')
  await page.reload()
  await expect(page.locator('.timeline')).toContainText('待研判 → 已确认')
  await page.getByLabel('下一状态').selectOption('fixing')
  await page.getByLabel('操作依据').fill('Phase 5 隔离验收：登记管理流程')
  await page.getByRole('button', { name: '更新状态', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登记修复声明' })).toBeVisible()
  await page.getByLabel('修复引用').fill('Phase5-E2E-声明流程验证')
  await page.getByLabel('修复说明').fill('仅验证声明保存功能，未修改原应用，不宣称实际修复')
  await page.getByRole('button', { name: '保存修复声明' }).click()
  await expect(page.locator('.record')).toContainText('仅验证声明保存功能')
  await page.getByLabel('下一状态').selectOption('pending_verification')
  await page.getByRole('button', { name: '更新状态', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登记实际复测' })).toBeVisible()
  await page.getByLabel('修复声明', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('复测运行').selectOption({ index: 1 })
  await expect(page.getByLabel('复测证据').locator('option').first()).toBeAttached()
  await page.getByLabel('复测证据').selectOption({ index: 0 })
  await page.getByLabel('测试范围').fill('使用历史真实运行验证证据关联功能，时间先于声明，不能证明修复')
  await page.getByLabel('复测说明').fill('历史证据不能支持新修复，结论保持未定')
  await page.getByRole('button', { name: '保存复测记录' }).click()
  await expect(page.locator('.record').filter({ hasText: '复测 #' })).toContainText('结论未定')
  await page.screenshot({ path: `${process.env.P5_EVIDENCE_DIR}/lifecycle.png`, fullPage: true })
  expect(errors).toEqual([])
})

test('真实接口空筛选与窄屏无水平溢出', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#findings')
  await page.getByLabel('来源', { exact: true }).selectOption('zap')
  await page.getByRole('button', { name: '筛选', exact: true }).click()
  await expect(page.getByText('没有符合条件的发现项')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `${process.env.P5_EVIDENCE_DIR}/narrow.png`, fullPage: true })
  await page.setViewportSize({ width: 900, height: 900 })
  await page.goto('/')
  await expect(page.locator('.tool-result').filter({ hasText: 'ZAP' })).toContainText('执行成功')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `${process.env.P5_EVIDENCE_DIR}/medium.png`, fullPage: true })
})

test('后端断网显示失败与重试入口', async ({ page }) => {
  // Only the network-failure case is intercepted; business scenarios above use live HTTP.
  await page.route('**/api/summary', route => route.abort('failed'))
  await page.goto('/')
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('button', { name: '重新加载' })).toBeVisible()
})
